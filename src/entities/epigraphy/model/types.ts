/** Знак письменности: картинка со стены и буквы, которые он может означать. */
export interface Sign {
  /** Идентификатор, он же имя файла с картинкой. */
  id: string
  /** Буквы знака. Одна — читается однозначно, несколько — выбирать придётся по смыслу. */
  letters: string[]
  /**
   * Что нарисовано — по этому слову знак ищется в таблице.
   *
   * Заполняется только там, где знак и правда что-то изображает: у египетских
   * пиктограмм («сова», «зигзаг»). У буквенного письма вроде славянского устава
   * описывать нечего, и поле остаётся пустым — знак там находят глазами по сетке.
   */
  picture?: string
}

/** Таблица знаков одного задания. */
export interface SignSet {
  /** Идентификатор, он же папка с картинками в `public/signs`. */
  id: string
  /** Короткое имя набора — им подписана кнопка переключателя: «Египет», «Славяне». */
  title: string
  /** Что за письменность: строка под заголовком таблицы. */
  script: string
  /** Откуда снята таблица: видно, на чём основаны данные. */
  source: string
  signs: Sign[]
}

/** Один знак разбираемой надписи. */
export interface Pick {
  /** Идентификатор знака либо WORD_BREAK — промежуток между словами. */
  id: string
  /** Выбранная буква неоднозначного знака; null — выбор ещё не сделан. */
  letter: string | null
}
