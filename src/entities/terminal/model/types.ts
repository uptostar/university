/** Сделанная попытка: какое слово ввели и сколько букв терминал засчитал. */
export interface Attempt {
  word: string
  /** Совпадений — букв, стоящих на своих местах. */
  likeness: number
}

/** Оценка хода: чем меньше worst, тем меньше кандидатов останется в худшем случае. */
export interface RankedGuess {
  word: string
  /** Сколько кандидатов останется при самом неудачном ответе. */
  worst: number
  /** Ожидаемое число оставшихся, если все кандидаты равновероятны. */
  expected: number
  /** Шанс, что это слово и есть пароль. */
  chance: number
}
